// ──────────────────────────────────────────────────────────────────────────
async function main() {
  console.log(`\n🔄 Reset Seed Keywords ${DRY_RUN ? "(DRY RUN)" : ""}`);
  console.log("━".repeat(50));

  // Step 1: Delete all contaminated seed keywords
  const seedCount = await prisma.ticketTypeKeyword.count({ where: { source: "seed" } });
  console.log(`\n[1] Deleting ${seedCount} contaminated seed keywords...`);
  if (!DRY_RUN) {
    await prisma.ticketTypeKeyword.deleteMany({ where: { source: "seed" } });
  }

  // Step 2: Load active types
  const types = await prisma.ticketType.findMany({
    where: { isActive: true },
    select: { id: true, key: true, nameAr: true },
  });
  const typeByKey = Object.fromEntries(types.map(t => [t.key, t]));

  // Step 3: Insert curated keywords
  console.log("\n[2] Inserting curated keywords...\n");
  let totalInserted = 0;

  for (const [typeKey, keywords] of Object.entries(CURATED)) {
    const dbType = typeByKey[typeKey];
    if (!dbType) {
      console.warn(`  ⚠️  Type "${typeKey}" not found in DB — skipping`);
      continue;
    }

    console.log(`  [${typeKey}] ${dbType.nameAr}: ${keywords.length} keywords`);
    if (DRY_RUN) { totalInserted += keywords.length; continue; }

    for (const [keyword, weight] of keywords) {
      // Skip if manual keyword already exists for this type
      const existing = await prisma.ticketTypeKeyword.findFirst({
        where: { keyword, typeId: dbType.id },
      });
      if (existing) continue;

      await prisma.ticketTypeKeyword.create({
        data: {
          keyword,
          typeId:    dbType.id,
          weight,
          source:    "seed",
          isLearned: false,
          confidence: 0.95,
          usageCount: 0,
          pendingReclassify: false,
        },
      });
      totalInserted++;
    }
  }

  // Summary
  const remaining = await prisma.ticketTypeKeyword.count();
  console.log(`\n${"━".repeat(50)}`);
  console.log(`🗑  Deleted seed keywords:   ${seedCount}`);
  console.log(`✅  Inserted curated:        ${totalInserted}`);
  console.log(`📚  Total keywords in DB:    ${remaining}`);
  if (DRY_RUN) console.log("\n⚠️  Dry run — nothing changed");

  await prisma.$disconnect();
}

main().catch(err => { console.error("❌", err); process.exit(1); });
